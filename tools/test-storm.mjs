const weapon = id => ({ type: 'weapon', weaponType: 'sword', name: 'Sword', damage: 5,
    durability: 5, maxDurability: 5, sigils: id ? [{ id }] : [] });
function fixture() {
    const scene = new MockScene();
    scene.gameState = new GameState(scene);
    scene.cardSystem = new CardSystem(scene);
    scene.gameState.currentFloor = 1;
    scene.gameState.actLocationIds = ['stormhatch', null, null];
    scene.gameState.playerHealth = scene.gameState.maxHealth = 100;
    scene.inventorySystem = { slots: [weapon()], slotSprites: [], playSlotStrikeAnimation() {} };
    scene.tutorialMode = true;
    scene.createDamageEffect = () => {};
    scene.markCompanionParticipated = () => {};
    return scene;
}
function enemy(scene, extra = {}, revealed = true) {
    return { revealed, sprite: Object.assign(scene.add.image(200, 100, 'enemy'), { x: 200, y: 100 }), data: {
        type: 'enemy', role: 'MELEE', health: 50, maxHealth: 50, attack: 5, features: [], ...extra } };
}
for (const act of [1, 2, 3]) {
    const scene = fixture();
    scene.gameState.currentFloor = (act - 1) * 15 + 1;
    scene.gameState.actLocationIds = [null, null, null];
    scene.gameState.actLocationIds[act - 1] = 'stormhatch';
    assert.deepEqual(offerableSigils(scene), ['conductive', 'shock', 'charged', 'twinSocket']);
    for (const [id, sigils] of Object.entries({ rainMite: [], stormBoar: [], cliffGull: [], stormRam: ['charged'], thunderCrow: ['shock'] })) {
        const data = buildEnemyCardFromDef(id, scene.gameState.currentFloor);
        assert.deepEqual(enemySigils(data).map(sigil => sigil.id), sigils);
        assert.equal(data.sprite, 'enemyPlaceholder');
        assert.equal(data.placeholderArt, true);
        assert.deepEqual(data.features, []);
    }
    const boss = scene.cardSystem.cardDataGenerator.createBossCard(act * 15, scene.gameState);
    assert.equal(boss.name, 'Tempest Roc');
    assert.equal(boss.tier, act);
    assert.deepEqual(enemySigils(boss).map(sigil => sigil.id), ['shock', 'summon']);
    assert.deepEqual(boss.abilities, [{ type: 'summon', enemyType: 'thunderCrow', chance: 0.25, count: 1 }]);
}
assert.ok(PLAYABLE_LOCATION_IDS.includes('stormhatch'), 'the approved complete roster enters the door pool');
const randomBefore = Math.random;
try {
    const scene = fixture(), cs = scene.cardSystem, gs = scene.gameState;
    const boss = enemy(scene, { type: 'boss' });
    cs.boardCards = [boss];
    Math.random = () => 0.1;
    assert.deepEqual(onWeaponSigilHit(scene, weapon('shock'), boss, { damageDealt: 1 }), []);
    Math.random = () => 0.099;
    onWeaponSigilHit(scene, weapon('shock'), boss, { damageDealt: 0 });
    assert.equal(boss.data.shockedTurns || 0, 0);
    assert.ok(onWeaponSigilHit(scene, weapon('shock'), boss, { damageDealt: 1 }).includes('shock'));
    assert.equal(boss.data.shockedTurns, 1);
    assert.equal(applyWeaponSigils(scene, weapon('charged'), boss, 5).damage, 7);
    new CombatTurnController(scene).processEnemyAttack(boss, 0);
    assert.equal(gs.playerHealth, 100);
    assert.equal(boss.data.shockedTurns, 0);
    assert.equal(applyWeaponSigils(scene, weapon('charged'), boss, 5).damage, 5);
    boss.data.frozen = 3;
    onWeaponSigilHit(scene, weapon('shock'), boss, { damageDealt: 1 });
    assert.equal(boss.data.frozen, 3, 'Shock cannot shorten a longer freeze');
    assert.equal(boss.data.shockedTurns, 0, 'ordinary freeze is not Shock');

    Math.random = () => 0.99;
    const attacking = fixture(), target = enemy(attacking), carried = weapon('growth');
    attacking.cardSystem.boardCards = [target];
    attacking.inventorySystem.slots = [carried];
    const attacker = { ...InventoryCombatUse, scene: attacking, slots: [carried],
        playWeaponStrikeEffect() {}, updateWeaponInfoText() {}, returnWeaponToSlotDelayed() {}, returnWeaponToSlot() {} };
    assert.equal(shockPlayer(attacking.gameState), true);
    assert.equal(shockPlayer(attacking.gameState), false, 'Shock does not stack missed attacks');
    assert.ok(CombatHud.collectPlayerEffectEntries.call({ gameState: attacking.gameState, scene: attacking })
        .some(entry => /Shocked/.test(entry.text)));
    const ap = attacking.gameState.actionsLeft;
    attacker.useWeapon(0, Object.assign(attacking.add.image(600, 300, 'weapon'), { x: 600, y: 300 }));
    assert.equal(attacking.gameState.playerShocked, true, 'invalid drops keep pending Shock');
    assert.equal(attacking.gameState.actionsLeft, ap);
    attacker.useWeapon(0, Object.assign(attacking.add.image(200, 100, 'weapon'), { x: 200, y: 100 }));
    assert.equal(attacking.gameState.playerShocked, false);
    assert.equal(attacking.gameState.actionsLeft, ap - 1);
    assert.equal(target.data.health, 50);
    assert.equal(carried.durability, 5);
    assert.equal(attacking.gameState.maxHealth, 100, 'a shocked miss cannot trigger on-hit sigils');
    assert.equal(attacking._enemyTurnPending, true, 'the missed action still queues the enemy response');
    attacker.useWeapon(0, Object.assign(attacking.add.image(200, 100, 'weapon'), { x: 200, y: 100 }));
    assert.equal(target.data.health, 45);
    assert.equal(carried.durability, 4);

    const companionScene = fixture(), companionTarget = enemy(companionScene);
    companionScene.cardSystem.boardCards = [companionTarget];
    const companion = { type: 'companion', attack: 3, attackStyle: 'melee' };
    companionScene.inventorySystem.slots = [companion];
    assert.equal(shockCompanion(companion), true);
    assert.match(getTooltipLines(companionScene, companion).body, /Shocked/);
    const controller = new CombatTurnController(companionScene);
    controller.runCompanionTurn({ companion, index: 0 });
    assert.equal(companionTarget.data.health, 50);
    assert.equal(companion.shockedTurns, 0);
    controller.runCompanionTurn({ companion, index: 0 });
    assert.equal(companionTarget.data.health, 47);
    shockCompanion(companion);
    companionScene.cardSystem.boardCards = [];
    controller.runCompanionTurn({ companion, index: 0 });
    assert.equal(companion.shockedTurns, 1, 'no target means no attack to miss');
    companionScene.cardSystem.boardCards = [companionTarget];
    companionScene._simInventory = [companion];
    companionScene._runCompanionTurns();
    assert.equal(companionTarget.data.health, 47);
    companionScene._runCompanionTurns();
    assert.equal(companionTarget.data.health, 44);

    const silkCompanionScene = fixture(), silkTarget = enemy(silkCompanionScene);
    const spinner = { type: 'companion', id: 'crystalSpiderlingCompanion', websEnemies: true, webSpinTurns: 1 };
    silkCompanionScene.cardSystem.boardCards = [silkTarget];
    silkCompanionScene.inventorySystem.slots = [spinner];
    shockCompanion(spinner);
    const spinnerController = new CombatTurnController(silkCompanionScene);
    spinnerController.runCompanionTurn({ companion: spinner, index: 0 });
    assert.equal(spinner.shockedTurns, 1, 'web-spinner cooldown does not spend Shock');
    spinnerController.runCompanionTurn({ companion: spinner, index: 0 });
    assert.equal(spinner.shockedTurns, 0);
    assert.equal(silkTarget.data.frozen || 0, 0, 'the shocked spinner misses its web attack');
    spinnerController.runCompanionTurn({ companion: spinner, index: 0 });
    assert.equal(silkTarget.data.webbedTurns, 1);

    const lightning = fixture(), hits = [];
    lightning.cardSystem.boardCards = Array.from({ length: 5 }, () => enemy(lightning));
    lightning.cardSystem.boardCards.push(enemy(lightning, {}, false));
    lightning.cardSystem.damageGemTarget = index => hits.push(index);
    lightning.cardSystem.playLightningArc = () => {};
    const gem = { ...weapon('conductive'), gemEffect: 'lightning', gemCount: 1 };
    lightning.cardSystem.applyWeaponGemEffect(0, gem, 5);
    assert.equal(new Set(hits).size, 4, 'main plus three secondary lightning targets');
    assert.ok(!hits.includes(5), 'Conductive never reaches a hidden enemy');
    hits.length = 0;
    lightning.cardSystem.applyWeaponGemEffect(0, { ...gem, sigils: [] }, 5);
    assert.equal(new Set(hits).size, 3);
    hits.length = 0;
    lightning.amuletManager = { modifyGemDamage: amount => amount, getLightningExtraBounces: () => 1 };
    lightning.cardSystem.applyWeaponGemEffect(0, secondGemView({ ...gem, gemEffect: 'fire', gem2Effect: 'lightning', gem2Count: 1 }), 5);
    assert.equal(new Set(hits).size, 5, 'Conductive combines with amulet reach and Twin Socket lightning');

    shockPlayer(attacking.gameState);
    attacking.inventorySystem.slots = [companion];
    shockCompanion(companion);
    const manager = new SaveManager();
    manager.saveCurrentRun(attacking.gameState, attacking.inventorySystem, attacking.cardSystem);
    const saved = manager.loadCurrentRun();
    assert.equal(saved.effects.playerShocked, true);
    assert.equal(saved.equipment.inventory[0].shockedTurns, 1);
    delete saved.effects.playerShocked;
    manager.safeSet(manager.RUN_SAVE_KEY, JSON.stringify(saved));
    assert.equal(manager.loadCurrentRun().effects.playerShocked, false);

    const stormScene = fixture(), crow = enemy(stormScene, { ...buildEnemyCardFromDef('thunderCrow', 1), attack: 5 });
    const ram = enemy(stormScene, { ...buildEnemyCardFromDef('stormRam', 1), attack: 11 });
    stormScene.cardSystem.boardCards = [crow, ram];
    const friend = { type: 'companion', attack: 3 };
    stormScene.inventorySystem.slots.push(friend);
    const choose = (...rolls) => () => rolls.shift();
    assert.equal(tryEnemyShock(stormScene, crow.data, 5, choose(0.1)), null);
    assert.equal(tryEnemyShock(stormScene, crow.data, 0, choose(0)), null);
    assert.equal(tryEnemyShock(stormScene, crow.data, 5, choose(0.099, 0.99)).companion, friend);
    assert.equal(friend.shockedTurns, 1);
    assert.equal(stormScene.gameState.playerShocked, false);
    assert.equal(tryEnemyShock(stormScene, crow.data, 5, choose(0.01, 0.99)), null, 'repeated companion Shock does not stack');
    Math.random = () => 0;
    const stormController = new CombatTurnController(stormScene);
    stormController.processEnemyAttack(crow, 0);
    assert.equal(stormScene.gameState.playerShocked, true);
    assert.equal(stormScene.gameState.playerHealth, 95);
    assert.equal(applyEnemyStrikeSigils(ram, stormScene.gameState, getEnemyHitAttack(ram, [crow, ram])), 16);
    stormController.processEnemyAttack(ram, 1);
    assert.equal(stormScene.gameState.playerHealth, 79, 'a Crow can set up a Ram in the same enemy phase');
    stormScene.gameState.playerShocked = false;
    stormScene.gameState.equippedArmor = { type: 'armor', protection: 20, durability: 10, maxDurability: 10 };
    stormController.processEnemyAttack(crow, 0);
    assert.equal(stormScene.gameState.playerShocked, false, 'fully blocked hits cannot shock');
    stormScene.gameState.equippedArmor.sigils = [{ id: 'fleetfoot' }];
    stormController.processEnemyAttack(crow, 0);
    assert.equal(stormScene.gameState.playerShocked, false, 'a dodged hit cannot shock');
    const headlessStorm = fixture();
    headlessStorm.cardSystem.boardCards = [enemy(headlessStorm, { ...crow.data }), enemy(headlessStorm, { ...ram.data })];
    headlessStorm.runEnemyTurn();
    assert.equal(headlessStorm.gameState.playerHealth, 79);
    assert.equal(headlessStorm.gameState.playerShocked, true);
    const summoning = fixture(), roc = enemy(summoning, { ...structuredClone(BOSSES.tempestRoc), frozen: 1 });
    summoning.cardSystem.boardCards = [roc];
    const calls = [];
    summoning.cardSystem.summonEnemy = id => { calls.push(id); return true; };
    const queue = new CombatTurnController(summoning);
    queue.tickHandWebs = () => {};
    queue.finishEnemyTurnEffects = () => {};
    queue.revealedEnemiesAttack();
    assert.deepEqual(calls, ['thunderCrow']);

    Math.random = () => 0.99;
    const spellScene = fixture(), spellCs = spellScene.cardSystem;
    const taunter = enemy(spellScene, { features: ['taunt'] });
    taunter.sprite.texture = { key: 'enemyPlaceholder' };
    const armored = enemy(spellScene, { armor: 99 });
    const spellBoss = enemy(spellScene, { type: 'boss' });
    const hidden = enemy(spellScene, {}, false);
    const pile = enemy(spellScene, { isBonePile: true, health: 1 });
    const shell = enemy(spellScene, { features: ['cocoon_shell'] });
    const loot = enemy(spellScene, { type: 'weapon' });
    const dying = enemy(spellScene, { health: 2 });
    const held = enemy(spellScene, { frozen: 3 });
    spellCs.boardCards = [taunter, armored, spellBoss, hidden, pile, shell, loot, dying, held];
    spellCs.damageGemTarget(1, 3, 'Test', 0xffcf7f, 'lightning');
    assert.equal(armored.data.health, 50, 'ordinary targeted damage still respects Taunt');
    const thunderclap = { type: 'magic', ...getMagic('thunderclap') };
    const caster = { ...InventoryCombatUse, scene: spellScene, slots: [thunderclap],
        cleanupCardSprites() {}, removeCard(index) { this.slots[index] = null; }, returnCardToSlot() {} };
    const spellAp = spellScene.gameState.actionsLeft;
    caster.useMagicCard(0, spellScene.add.image(200, 100, 'thunderclap'));
    assert.equal(caster.slots[0], null);
    assert.equal(spellScene.gameState.actionsLeft, spellAp - 1);
    for (const target of [taunter, armored, spellBoss]) {
        assert.equal(target.data.health, 47);
        assert.equal(target.data.shockedTurns, 1);
    }
    assert.equal(hidden.data.health, 50);
    assert.equal(hidden.data.shockedTurns || 0, 0);
    for (const target of [shell, loot]) assert.equal(target.data.health, 50);
    assert.equal(pile.data.health, 1);
    assert.equal(held.data.health, 47);
    assert.equal(held.data.frozen, 3);
    assert.equal(dying.data.shockedTurns || 0, 0, 'defeated targets cannot pass Shock onto their loot');
    spellCs.boardCards = [hidden, pile, shell, loot];
    caster.slots = [thunderclap];
    assert.equal(applyThunderclap(spellCs), 0);
    caster.useMagicCard(0, spellScene.add.image(200, 100, 'thunderclap'));
    assert.equal(caster.slots[0], thunderclap);
    assert.equal(spellScene.gameState.actionsLeft, spellAp - 1, 'invalid casts do not spend AP');
    assert.match(InventoryView.describeMagicCard.call({ scene: spellScene }, thunderclap), /3 lightning.*including bosses/);
    assert.equal(getGlowCardFrame('thunderclap'), 1);
    assert.ok(enchantableMagicTypes(1).includes('thunderclap'));
    const enchanted = weapon();
    assert.equal(applyEnchantToWeapon(enchanted, 'thunderclap'), true);
    assert.equal(getEnchantChance('thunderclap'), 0.1);
    assert.match(describeWeaponEnchant(spellScene, enchanted), /10%.*struck enemy/);
    enchanted.sigils = [{ id: 'shock' }];
    assert.equal(cardSigils(enchanted).filter(sigil => sigil.id === 'shock').length, 1);
    const enchantedTarget = enemy(spellScene), untouched = enemy(spellScene);
    spellCs.boardCards = [enchantedTarget, untouched];
    let procRolls = 0;
    Math.random = () => { procRolls++; return 0.01; };
    assert.equal(spellCs.rollWeaponEnchant(enchanted), null, 'the enchant does not add a second rarity roll');
    onWeaponSigilHit(spellScene, enchanted, enchantedTarget, { damageDealt: 1 });
    assert.equal(procRolls, 1);
    assert.equal(enchantedTarget.data.shockedTurns, 1);
    assert.equal(untouched.data.shockedTurns || 0, 0);
} finally { Math.random = randomBefore; }
console.log('Storm checks passed: all-act roster/boss, Shock/Charged/reach, player/companion skips, Thunderclap targets/armor/Taunt/consumption, single-roll enchant, HUD, saves and headless parity.');

"""Pack loose sprites into sheets (tools/packed-sprites.json), so the game loads one file for each
group instead of dozens. Edit the PNGs under assets/_sources/packed/, then run:

    python tools/pack-sprites.py

It writes the sheet PNGs and src/content/assets/packedSprites.js (frame numbers). At boot the game
cuts every frame back into its old texture key (buildPackedSprites), so nothing else changes.
`--check` rewrites nothing and exits 1 if a sheet is out of date."""
import json, pathlib, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((ROOT / 'tools' / 'packed-sprites.json').read_text(encoding='utf-8'))
check = '--check' in sys.argv
stale = []
module = {'sheets': []}
for sheet in spec['sheets']:
    cw, ch, cols = sheet['cellWidth'], sheet['cellHeight'], sheet['columns']
    rows = -(-len(sheet['entries']) // cols)
    out = Image.new('RGBA', (cols * cw, rows * ch), (0, 0, 0, 0))
    entries = []
    for frame, e in enumerate(sheet['entries']):
        im = Image.open(ROOT / e['source']).convert('RGBA')
        assert im.width <= cw and im.height <= ch, (e['key'], im.size, (cw, ch))
        out.alpha_composite(im, ((frame % cols) * cw, (frame // cols) * ch))   # top-left of its cell, never scaled
        entries.append({'key': e['key'], 'frame': frame, 'width': im.width, 'height': im.height})
    path = ROOT / sheet['path']
    if check:
        if not path.exists() or Image.open(path).convert('RGBA').tobytes() != out.tobytes(): stale.append(sheet['path'])
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        out.save(path, optimize=True)
        print('wrote', sheet['path'], out.size, len(entries), 'sprites')
    module['sheets'].append({'key': sheet['key'], 'path': sheet['path'], 'frameWidth': cw, 'frameHeight': ch, 'entries': entries})

js = ('// GENERATED by tools/pack-sprites.py from tools/packed-sprites.json. Do not edit by hand:\n'
      '// change the PNGs in assets/_sources/packed/ and run the script again.\n'
      '//\n// Loose sprites packed into a few sheets, so boot downloads one file per group. At boot\n'
      '// buildPackedSprites cuts each frame back into a texture under its old key, so the rest of\n'
      '// the game still asks for `trap`, `fireBall1` and so on.\n\n'
      'export const PACKED_SHEETS = Object.freeze(' + json.dumps(module['sheets'], indent=2) + ');\n\n'
      '/** Cut every packed sprite back into a texture of its own old key. Skips any already there. */\n'
      'export function buildPackedSprites(scene) {\n'
      '    let built = 0;\n'
      '    for (const sheet of PACKED_SHEETS) {\n'
      '        if (!scene?.textures?.exists?.(sheet.key)) continue;\n'
      '        for (const { key, frame, width, height } of sheet.entries) {\n'
      '            if (scene.textures.exists(key)) continue;\n'
      '            const texture = scene.textures.createCanvas(key, width, height);\n'
      '            texture.drawFrame(sheet.key, frame, 0, 0);\n'
      '            texture.refresh();\n'
      '            built++;\n'
      '        }\n'
      '    }\n'
      '    return built;\n'
      '}\n')
mod = ROOT / 'src' / 'content' / 'assets' / 'packedSprites.js'
if check:
    if not mod.exists() or mod.read_text(encoding='utf-8') != js: stale.append(str(mod.relative_to(ROOT)))
    if stale: print('out of date:', ', '.join(stale)); sys.exit(1)
    print('packed sprites are up to date')
else:
    mod.write_text(js, encoding='utf-8'); print('wrote', mod.relative_to(ROOT))
